// TranslateRegion переводит английский район в русский. Если перевода нет,
// возвращается исходная строка — лучше показать английское название,
// чем пустое поле.
func TranslateRegion(en string) string {
	if ru, ok := ruRegions[en]; ok && ru != "" {
		return ru
	}
	return en
}
